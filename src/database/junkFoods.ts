export function getJunkFoodById(id: string): JunkFoodItem | undefined {
  return COMPREHENSIVE_JUNK_FOODS.find(j => j.id === id);
}

export function calculateMetabolicPenalty(junkFoodIds: string[]): { totalCal: number; sodiumTotal: number; insulinSpikeRisk: 'low' | 'medium' | 'high' | 'severe' } {
  let totalCal = 0;
  let sodiumTotal = 0;
  let avgGI = 0;

  for (const id of junkFoodIds) {
    const item = getJunkFoodById(id);
    if (item) {
      totalCal += item.calories;
      sodiumTotal += item.sodiumMg;
      avgGI += item.glycemicIndex;
    }
  }

  const meanGI = junkFoodIds.length > 0 ? avgGI / junkFoodIds.length : 0;
  let insulinSpikeRisk: 'low' | 'medium' | 'high' | 'severe' = 'low';
  if (meanGI > 85) insulinSpikeRisk = 'severe';
  else if (meanGI > 75) insulinSpikeRisk = 'high';
  else if (meanGI > 60) insulinSpikeRisk = 'medium';

  return { totalCal, sodiumTotal, insulinSpikeRisk };
}
